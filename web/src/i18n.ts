export type TKey = keyof typeof th
const dicts: Record<Lang, Record<TKey, string>> = { th, en }

export function translate(lang: Lang, key: TKey, vars: Record<string, string | number> = {}) {
  return dicts[lang][key].replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}

export function useT() {
  const lang = useStore((s) => s.lang)
  return (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars)
}

export function setLang(lang: Lang) {
  useStore.setState({ lang })
  try {
    localStorage.setItem('lang', lang)
  } catch {
    /* storage blocked: language lasts for this tab only */
  }
}
