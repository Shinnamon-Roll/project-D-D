// update rewrites the generated Go data files from the docs instead of comparing:
//
//	go test ./internal/rules -run 'MatchDoc' -update
var update = flag.Bool("update", false, "rewrite classes_data.go, roster_default.go and roster_legend.go from docs/design")

const designDir = "../../docs/design/"

// docJSON decodes the "## JSON (machine-readable)" block of a docs/design file into v, rejecting unknown keys.
func docJSON(t *testing.T, name string, v any) {
	t.Helper()
	b, err := os.ReadFile(designDir + name)
	if err != nil {
		t.Fatal(err)
	}
	_, block, ok := strings.Cut(string(b), "## JSON (machine-readable)\n\n```json\n")
	block, _, ok2 := strings.Cut(block, "```")
	if !ok || !ok2 {
		t.Fatalf("%s: no JSON block", name)
	}
	d := json.NewDecoder(strings.NewReader(block))
	d.DisallowUnknownFields()
	if err := d.Decode(v); err != nil {
		t.Fatalf("%s: %v", name, err)
	}
}

// docClasses reads every docs/design/classes/<id>.md JSON block, in file name order.
func docClasses(t *testing.T) []Class {
	t.Helper()
	files, err := filepath.Glob(designDir + "classes/[a-z]*.md")
	if err != nil || len(files) == 0 {
		t.Fatalf("class docs: %v %v", files, err)
	}
	var out []Class
	for _, f := range files {
		var c Class
		docJSON(t, "classes/"+filepath.Base(f), &c)
		out = append(out, c)
	}
	return out
}

// syncGo compares got with the doc data, or with -update writes fn() returning want into file.
func syncGo(t *testing.T, file, source, fn string, got, want any) {
	t.Helper()
	if *update {
		var b strings.Builder
		fmt.Fprintf(&b, "// Code generated by `go test ./internal/rules -run MatchDoc -update` from %s. DO NOT EDIT.\n\n", source)
		fmt.Fprintf(&b, "package rules\n\nfunc %s() %s {\n\treturn ", fn, goType(reflect.TypeOf(want)))
		goLit(&b, reflect.ValueOf(want), true)
		b.WriteString("\n}\n")
		src, err := format.Source([]byte(b.String()))
		if err != nil {
			t.Fatalf("format %s: %v", file, err)
		}
		if old, _ := os.ReadFile(file); !bytes.Equal(old, src) {
			if err := os.WriteFile(file, src, 0o644); err != nil {
				t.Fatal(err)
			}
			t.Logf("wrote %s (rebuild and rerun to compare)", file)
		}
		return
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("internal/rules/%s differs from %s; run: go test ./internal/rules -run MatchDoc -update", file, source)
	}
}

func goType(t reflect.Type) string { return strings.ReplaceAll(t.String(), "rules.", "") }

// goLit writes v as a Go composite literal. Zero fields are left out; typed=false elides the type (slice elements).
func goLit(b *strings.Builder, v reflect.Value, typed bool) {
	switch v.Kind() {
	case reflect.String:
		b.WriteString(strconv.Quote(v.String()))
	case reflect.Int:
		b.WriteString(strconv.FormatInt(v.Int(), 10))
	case reflect.Slice:
		if typed {
			b.WriteString(goType(v.Type()))
		}
		multi := v.Type().Elem().Kind() == reflect.Struct && v.Type().Elem() != reflect.TypeOf(L{})
		b.WriteString("{")
		for i := range v.Len() {
			if multi {
				b.WriteString("\n")
			} else if i > 0 {
				b.WriteString(", ")
			}
			goLit(b, v.Index(i), false)
			if multi {
				b.WriteString(",")
			}
		}
		if multi && v.Len() > 0 {
			b.WriteString("\n")
		}
		b.WriteString("}")
	case reflect.Struct:
		if typed {
			b.WriteString(goType(v.Type()))
		}
		if v.Type() == reflect.TypeOf(L{}) {
			fmt.Fprintf(b, "{%q, %q}", v.Field(0).String(), v.Field(1).String())
			return
		}
		multi := false
		for i := range v.NumField() {
			multi = multi || v.Field(i).Kind() == reflect.Slice
		}
		b.WriteString("{")
		first := true
		for i := range v.NumField() {
			f := v.Field(i)
			if f.IsZero() {
				continue
			}
			switch {
			case multi:
				b.WriteString("\n")
			case !first:
				b.WriteString(", ")
			}
			first = false
			b.WriteString(v.Type().Field(i).Name + ": ")
			goLit(b, f, true)
			if multi {
				b.WriteString(",")
			}
		}
		if multi {
			b.WriteString("\n")
		}
		b.WriteString("}")
	default:
		panic("goLit: unsupported kind " + v.Kind().String())
	}
}
